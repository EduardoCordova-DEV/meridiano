test('tema: aplica la elección antes de descargar React', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Cambiar a modo oscuro' }).click()
  let release = () => {}
  const gate = new Promise<void>((resolve) => { release = resolve })
  await page.route('**/src/main.tsx', async (route) => { await gate; await route.continue() })
  const navigation = page.reload({ waitUntil: 'domcontentloaded' })
  try {
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
    await expect(page.locator('#root')).toBeEmpty()
    await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(17, 27, 25)')
    await expect(page.locator('html')).toHaveCSS('color-scheme', 'dark')
  } finally {
    release()
    await navigation
    await page.unroute('**/src/main.tsx')
  }
  await expect(page.getByRole('button', { name: 'Cambiar a modo claro' })).toBeVisible()
})

