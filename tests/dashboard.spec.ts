test('accesibilidad y tamaño mínimo: contraste, etiquetas, teclado y relojes sin recortes', async ({ page }) => {
  await page.goto('/')
  expect(await accessibilityIssues(page)).toEqual([])
  await page.getByRole('button', { name: '12 h', exact: true }).click()
  await page.setViewportSize({ width: 320, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(await page.locator('.time-display').evaluateAll((elements) => elements.every((element) => element.scrollWidth <= element.clientWidth))).toBe(true)
  await page.getByRole('button', { name: 'Convertir horario', exact: true }).click()
  expect(await accessibilityIssues(page)).toEqual([])
  await page.getByRole('button', { name: 'Añadir reloj', exact: true }).click()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Cerrar diálogo' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  // Scrollable native dialogs add a container stop before browser chrome.
  const dialog = page.getByRole('dialog')
  if (await dialog.evaluate((element) => element === document.activeElement)) await page.keyboard.press('Shift+Tab')
  // Native dialogs can visit browser chrome, but must not focus the inert page.
  expect(await page.evaluate(() => !document.hasFocus() || Boolean(document.querySelector('dialog')?.contains(document.activeElement)))).toBe(true)
  if (!(await page.evaluate(() => document.hasFocus()))) await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Añadir reloj' })).toBeFocused()
  expect(await accessibilityIssues(page)).toEqual([])
})

